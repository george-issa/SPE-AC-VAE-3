def test_save_load_roundtrip(tmp_path):
    model = tiny_model(seed=1, latent_dim=5, num_poles=7)
    path = str(tmp_path / "m.pt")
    save_model(model, path, note="hello", metrics={"w1": 0.3})

    loaded = load_model(path)
    assert loaded.config == model.config
    assert not loaded.training, "a loaded model should be in eval mode"
    for (ka, va), (kb, vb) in zip(model.state_dict().items(),
                                  loaded.state_dict().items()):
        assert ka == kb and torch.equal(va, vb)

    ck = load_checkpoint(path)
    assert ck["meta"]["note"] == "hello"
    assert ck["format"] == 1 and "spevae_version" in ck


def test_loaded_model_reproduces_predictions(tmp_path):
    model = tiny_model(seed=2)
    path = str(tmp_path / "m.pt")
    save_model(model, path)
    loaded = load_model(path)

    G = torch.rand(3, 41) * 0.4 + 0.3
    G[:, -1] = 1.0 - G[:, 0]
    a = model.continue_(G, beta=BETA, omega=torch.linspace(-6, 6, 201))
    b = loaded.continue_(G, beta=BETA, omega=torch.linspace(-6, 6, 201))
    assert torch.allclose(a["A"], b["A"], atol=1e-12)


def test_safe_overrides_are_allowed_and_unsafe_ones_are_not(tmp_path):
    model = tiny_model(seed=3)
    path = str(tmp_path / "m.pt")
    save_model(model, path)
    # Cache size does not touch the weights.
    assert load_model(path, cache_limit=1)._cache_limit == 1
    # A different pole count does, and must fail rather than load silently.
    with pytest.raises(RuntimeError):
        load_model(path, num_poles=model.num_poles + 3)


def test_a_non_checkpoint_is_rejected(tmp_path):
    path = str(tmp_path / "junk.pt")
    torch.save({"hello": "world"}, path)
    with pytest.raises(ValueError, match="does not look like"):
        load_model(path)


def test_legacy_checkpoint_still_loads(tmp_path):
    """Pre-format-1 files stored the training script's argparse dump."""
    model = tiny_model(seed=4, latent_dim=8, num_poles=12)
    ref = SPEVAE(latent_dim=8, num_poles=12, omega_c=20.0, d_model=32,
                 enc_layers=3, dec_layers=2, n_heads=4, d_ff=256, n_matsubara=16)
    path = str(tmp_path / "old.pt")
    torch.save({"state_dict": ref.state_dict(),
                "config": {"latent_dim": 8, "num_poles": 12, "d_model": 32,
                           "steps": 100, "batch_size": 48}}, path)
    loaded = load_model(path)
    assert loaded.num_poles == 12 and loaded.latent_dim == 8


