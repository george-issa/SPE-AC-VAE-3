def test_refinement_recovers_a_decodable_spectrum():
    """The mechanism, isolated from the checkpoint's quality.

    The data comes from the decoder, so a code exists that explains it exactly.
    Refinement must find one: chi^2 down to the calibrated floor, and the
    spectrum far closer to the truth than the amortised pass.
    """
    model = tiny_model(seed=5)
    mg, poles_true, _ = decodable_dataset(model, seed=5)
    A_true = poles_true.spectral(torch.as_tensor(OMEGA).float())[0].numpy()

    amortised = model.continue_(
        mg.mean.unsqueeze(0).float(), beta=BETA, tau=mg.tau.float(),
        sigma=mg.sigma_mean.unsqueeze(0).float(),
        omega=torch.as_tensor(OMEGA).float())
    r0 = spectral_report(amortised["A"][0].numpy(), A_true, OMEGA,
                         resolution=math.pi / BETA)

    # Many steps because the decoder here has *random* weights, which makes the
    # z -> A map badly conditioned; a trained checkpoint reached ratio 1.09 in
    # 1500.  This is a test of the optimiser, not of convergence speed.
    res = refine_latent(model, mg, RefineConfig(steps=4000, lr=0.1, patience=600))
    A1 = res.spectral(torch.as_tensor(OMEGA).float()).numpy()[0]
    r1 = spectral_report(A1, A_true, OMEGA, resolution=math.pi / BETA)

    assert res.chi2 < res.chi2_init / 100.0, (res.chi2_init, res.chi2)
    assert res.chi2_ratio < 1.5, f"did not reach the noise floor: {res.chi2_ratio}"
    assert r1["l2_rel"] < 0.5 * r0["l2_rel"], (r0["l2_rel"], r1["l2_rel"])
    assert r1["w1"] < 0.5 * r0["w1"], (r0["w1"], r1["w1"])


@pytest.mark.parametrize("residue_mode", ["real", "complex"])
def test_refinement_preserves_every_structural_guarantee(residue_mode):
    """The whole point of refining z rather than the weights.

    Positivity is the one guarantee that is mode-dependent: structural with real
    residues, a penalty with complex ones.  The test asserts it only where it is
    actually promised, and checks the zero-sum tail in both.
    """
    model = tiny_model(seed=6, residue_mode=residue_mode)
    mg, _, _ = decodable_dataset(model, seed=6, n_tau=61, n_bins=200)
    res = refine_latent(model, mg, RefineConfig(steps=200, lr=0.1))
    p = res.poles
    assert (p.gamma > 0).all(), "causality"
    assert (p.a > 0).all(), "positive weights"
    assert torch.allclose(p.a.sum(-1), torch.ones(p.shape[0]), atol=1e-4), "sum rule"
    assert torch.allclose(p.b.sum(-1), torch.zeros(p.shape[0]), atol=1e-6), "1/w^2 tail"
    assert (p.gamma * mg.beta >= model.gamma_min - 1e-9).all(), "width floor"
    A = res.spectral(torch.linspace(-40, 40, 4001))
    if residue_mode == "real":
        assert (A >= 0).all(), "positivity is structural in real mode"
    else:
        # The dispersive parts must stay inside their per-pole bound, and the
        # mode must actually be exercising them -- an identically-zero b would
        # mean the complex branch silently degenerated to the real one.
        assert (p.b.abs() <= p.a + 1e-8).all(), "|b_p| <= a_p bound"
        assert float(p.b.abs().max()) > 0.0, "complex mode produced b == 0"


def test_refinement_leaves_the_model_untouched():
    """No weight moves, and requires_grad flags are restored."""
    model = tiny_model(seed=7)
    mg, _, _ = decodable_dataset(model, seed=7, n_tau=41, n_bins=100)
    before = {k: v.clone() for k, v in model.state_dict().items()}
    flags = [p.requires_grad for p in model.parameters()]
    refine_latent(model, mg, RefineConfig(steps=50))
    for k, v in model.state_dict().items():
        assert torch.equal(v, before[k]), f"{k} moved"
    assert [p.requires_grad for p in model.parameters()] == flags


def test_a_stronger_prior_keeps_the_code_closer_to_the_encoder():
    model = tiny_model(seed=8)
    mg, _, _ = decodable_dataset(model, seed=8, n_tau=41, n_bins=100)
    weak = refine_latent(model, mg, RefineConfig(steps=300, lr=0.05,
                                                 prior_weight=1e-6))
    strong = refine_latent(model, mg, RefineConfig(steps=300, lr=0.05,
                                                   prior_weight=1e4))
    assert float(strong.z.norm()) < float(weak.z.norm())
    assert strong.prior_term > weak.prior_term


def test_prior_binding_flag_reports_the_map_balance():
    """When the data term dwarfs the prior, say so rather than implying MAP."""
    model = tiny_model(seed=9)
    mg, _, _ = decodable_dataset(model, seed=9, n_tau=41, n_bins=100)
    res = refine_latent(model, mg, RefineConfig(steps=400, lr=0.05, patience=100))
    assert res.data_term >= 0 and res.prior_term >= 0
    assert res.prior_is_binding == (res.data_term < 100.0 * res.prior_term)


def test_per_bin_refinement_gives_one_code_per_bin():
    model = tiny_model(seed=10)
    mg, _, _ = decodable_dataset(model, seed=10, n_tau=41, n_bins=12)
    res = refine_latent(model, mg, RefineConfig(steps=40, per_bin=True))
    assert res.z.shape == (mg.n_bins, model.latent_dim)
    assert res.poles.shape[0] == mg.n_bins


def test_refinement_stops_at_the_calibrated_floor_not_at_one():
    """target_ratio is relative to chi2_target, which is generally not 1."""
    model = tiny_model(seed=11)
    mg, _, _ = decodable_dataset(model, seed=11)
    res = refine_latent(model, mg, RefineConfig(steps=6000, lr=0.1,
                                                target_ratio=1.0, patience=600))
    if res.converged:
        assert res.chi2 <= res.chi2_target * 1.0 + 1e-9
        assert res.steps_run < 6000
