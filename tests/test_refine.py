"""Tests for checkpoint I/O and latent refinement.

The load-bearing test is :func:`test_refinement_recovers_a_decodable_spectrum`:
it generates data *from the decoder itself*, so the answer is known to be inside
the model's range, and checks that refinement finds it.  That isolates the
optimisation from the quality of whatever checkpoint happens to be around --
without it, a weak model and a broken refiner look identical.
"""

import math
import os

import numpy as np
import pytest
import torch

from spevae import (
    RefineConfig,
    load_checkpoint,
    load_model,
    refine_latent,
    save_model,
)
from spevae.data import from_bins
from spevae.models import SPEVAE
from spevae.metrics import spectral_report

BETA = 10.0
OMEGA = np.linspace(-10, 10, 801)


def tiny_model(seed=0, latent_dim=6, num_poles=8, residue_mode="real"):
    torch.manual_seed(seed)
    return SPEVAE(latent_dim=latent_dim, num_poles=num_poles, omega_c=20.0,
                  d_model=32, enc_layers=2, dec_layers=2, n_heads=4, d_ff=64,
                  n_matsubara=8, residue_mode=residue_mode).eval()


def decodable_dataset(model, seed=0, n_tau=81, n_bins=800, noise=1e-3):
    """Bins generated by the model's own decoder: the answer is in its range."""
    torch.manual_seed(seed)
    tau = torch.linspace(0, BETA, n_tau)
    x = tau / BETA
    z_true = torch.randn(1, model.latent_dim)
    with torch.no_grad():
        poles = model.decode(z_true, torch.ones(1), BETA)
        clean = model.forward_map(BETA, tau.device, tau.dtype)(
            poles, x, kernel_matrix=model.kernel_matrix(BETA, x))[0]
    g = torch.Generator().manual_seed(seed + 1)
    d = (tau.reshape(-1, 1) - tau.reshape(1, -1)).abs() / BETA
    R = 0.8 * torch.exp(-d / 0.1) + 0.2 * torch.eye(n_tau)
    eta = torch.randn(n_bins, n_tau, generator=g) @ torch.linalg.cholesky(R).T
    mg = from_bins((clean.unsqueeze(0) + eta * noise).double(), BETA,
                   tau=tau.double(), dtype=torch.float64)
    return mg, poles.to_physical(BETA), z_true


